/**
 * Regenerates the palette fallback values from `@carbon/themes`.
 *
 * Usage: pnpm run generate:palettes
 *
 * Outputs:
 * - src/types/Palette.d.ts  (palette type)
 * - src/light-mode.ts       (Carbon White theme)
 * - src/dark-mode.ts        (Carbon Gray 100 theme)
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { g100, white } from '@carbon/themes';

type Theme = Record<string, unknown>;

/** UI tokens used by the editor theme. */
const uiTokens = [
  'background',
  'layerAccent01',
  'layer01',
  'layer02',
  'layerSelected01',
  'backgroundSelected',
  'highlight',
  'textPrimary',
  'textSecondary',
  'textHelper',
  'borderSubtle01',
  'focus'
];

/** All `syntax*` tokens defined by Carbon. */
const syntaxTokens = Object.keys(g100)
  .filter(key => key.startsWith('syntax'))
  .toSorted();

const tokens = [...uiTokens, ...syntaxTokens];

const root = path.resolve(import.meta.dirname, '..');
const header = '// This file is generated by scripts/generate-palettes.ts. Do not edit manually.\n';

const toCssVariable = (key: string): string =>
  `--cds-${key.replaceAll(/(?<=[a-z])(?=[A-Z0-9])/g, '-').toLowerCase()}`;

const valueOf = (theme: Theme, name: string, key: string): string => {
  const value = theme[key];
  if (typeof value !== 'string') {
    throw new TypeError(`Token "${key}" is missing in the ${name} theme.`);
  }
  return value;
};

const writePaletteType = (): void => {
  const fields = tokens.map(key => `  /** \`${toCssVariable(key)}\` */\n  ${key}: string;`);
  const content = [
    header,
    '/**',
    ' * Fallback values for the Carbon color tokens used by the theme.',
    ' * Each key is the camelCase form of a `--cds-*` CSS custom property name.',
    ' * @see https://www.carbondesignsystem.com/building-blocks/foundations/color/tokens',
    ' */',
    'export type Palette = {',
    ...fields,
    '};',
    ''
  ].join('\n');
  writeFileSync(path.resolve(root, 'src/types/Palette.d.ts'), content);
};

const writePalette = (
  file: string,
  exportName: string,
  mode: string,
  themeName: string,
  theme: Theme
): void => {
  const entries = tokens.map(key => `  ${key}: '${valueOf(theme, themeName, key)}',`);
  const content = [
    header,
    "import type { Palette } from '@/types/Palette';",
    '',
    '/**',
    ` * Fallback colors for ${mode} mode, taken from the Carbon ${themeName} theme.`,
    ' * Used only when the corresponding `--cds-*` CSS custom property is not defined.',
    ' */',
    `export const ${exportName}: Palette = {`,
    ...entries,
    '};',
    ''
  ].join('\n');
  writeFileSync(path.resolve(root, file), content);
};

writePaletteType();
writePalette('src/light-mode.ts', 'lightPalette', 'light', 'White', white);
writePalette('src/dark-mode.ts', 'darkPalette', 'dark', 'Gray 100', g100);

console.log(`Generated palettes with ${tokens.length.toString()} tokens.`);
